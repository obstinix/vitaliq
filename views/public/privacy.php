<div class="wrap wrap--narrow section prose">
  <h2>What we collect</h2>
  <ul>
    <li><strong>Identity and contact:</strong> name, date of birth, mobile number, optionally sex and email.</li>
    <li><strong>Test details:</strong> test type, reason, symptoms and when they started, contact with a confirmed case, and the collection address and time slot.</li>
    <li><strong>Results:</strong> the outcome recorded by the laboratory, visible to you only after it is authorised.</li>
  </ul>
  <p>We do not ask for government ID numbers, insurance details or any medical history beyond what affects the test.</p>

  <h2>Who can see it</h2>
  <p>You, and the staff who process your request: administrators, and the phlebotomist assigned to your collection, who sees only what is needed for the visit. Every status change records who made it and when. Public statistics are aggregated, and counts below five are not shown.</p>

  <h2>How it is protected</h2>
  <p>Passwords are stored as Argon2id hashes, never in readable form. Sessions expire after inactivity. Reset links are single-use and expire after 30 minutes. Network addresses are stored only as keyed hashes for rate limiting and audit.</p>

  <h2>Limits of this demonstration</h2>
  <p>This deployment is a student project and has not been through a regulatory compliance assessment. Do not enter real health information into it.</p>
